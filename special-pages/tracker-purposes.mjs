/**
 * Builds the fallback company → purposes table used by the New Tab Page
 * Protections Report, from a local checkout of DuckDuckGo Tracker Radar
 * (https://github.com/duckduckgo/tracker-radar).
 *
 * Native can send each company's Tracker Radar categories and fingerprinting
 * score with the weekly stats. When it doesn't, the report looks the company
 * up in this table instead.
 *
 * It also records which details about a device (graphics card, screen, fonts…)
 * each company's scripts are known to read, for the "How they try to recognize
 * you" view. A company counts if any of its scripts seen on at least
 * `MIN_SCRIPT_PREVALENCE` of sites reads one of the APIs in `SURFACES`.
 *
 * A company can own hundreds of domains, so simply merging all their
 * categories would give every big company every purpose. Instead a purpose is
 * kept only if the domains carrying it make up at least `MIN_SHARE` of the
 * company's total prevalence.
 *
 * Usage (from `special-pages/`):
 *   npm run build-tracker-purposes -- [--radar <path>] [--region US]
 *
 * `--radar` defaults to a `tracker-radar` checkout at the repo root.
 */
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import * as prettier from 'prettier';
import { parseArgs, cwd } from '../scripts/script-utils.js';
import { FINGERPRINTING_THRESHOLD, PURPOSES, SURFACES } from './pages/new-tab/app/protections/utils/purposes.js';

const CWD = cwd(import.meta.url);
const OUTPUT = join(CWD, 'pages/new-tab/app/protections/data/tracker-purposes.js');

/** Ignore companies found on fewer than this fraction of top sites */
const MIN_PREVALENCE = 0.001;
/** Keep a purpose when its domains account for at least this share of the company's prevalence */
const MIN_SHARE = 0.25;
/** Ignore rare scripts when deciding what a company is known to read */
const MIN_SCRIPT_PREVALENCE = 0.0005;

const args = parseArgs(process.argv.slice(2), []);
const radarDir = args.radar ? join(process.cwd(), args.radar) : join(CWD, '../tracker-radar');
const region = args.region || 'US';
const domainsDir = join(radarDir, 'domains', region);

/** @type {Map<string, {total: number, byPurpose: Map<string, number>, surfaces: Set<string>}>} */
const companies = new Map();

for (const file of readdirSync(domainsDir)) {
    if (!file.endsWith('.json')) continue;
    const domain = JSON.parse(readFileSync(join(domainsDir, file), 'utf8'));
    // must match the `displayName` native sends, which comes from the same data
    const name = domain.owner?.displayName || domain.owner?.name;
    const prevalence = domain.prevalence ?? 0;
    if (!name || !prevalence) continue;

    const key = name.toLowerCase();
    const company = companies.get(key) ?? { total: 0, byPurpose: new Map(), surfaces: new Set() };
    company.total += prevalence;
    const categories = new Set(domain.categories ?? []);
    for (const purpose of PURPOSES) {
        const matches =
            purpose.id === 'fingerprinting'
                ? (domain.fingerprinting ?? 0) >= FINGERPRINTING_THRESHOLD
                : purpose.categories.some((c) => categories.has(c));
        if (matches) company.byPurpose.set(purpose.id, (company.byPurpose.get(purpose.id) ?? 0) + prevalence);
    }
    for (const resource of domain.resources ?? []) {
        if ((resource.prevalence ?? 0) < MIN_SCRIPT_PREVALENCE) continue;
        for (const api of Object.keys(resource.apis ?? {})) {
            for (const surface of SURFACES) {
                if (surface.apis.some((prefix) => api.startsWith(prefix))) company.surfaces.add(surface.id);
            }
        }
    }
    companies.set(key, company);
}

/** @type {Record<string, number>} */
const table = {};
/** @type {Record<string, number>} */
const surfaces = {};
for (const [key, company] of [...companies].sort(([a], [b]) => a.localeCompare(b))) {
    if (company.total < MIN_PREVALENCE) continue;
    let mask = 0;
    PURPOSES.forEach((purpose, bit) => {
        if ((company.byPurpose.get(purpose.id) ?? 0) / company.total >= MIN_SHARE) mask |= 1 << bit;
    });
    if (mask) table[key] = mask;

    let surfaceMask = 0;
    SURFACES.forEach((surface, bit) => {
        if (company.surfaces.has(surface.id)) surfaceMask |= 1 << bit;
    });
    if (surfaceMask) surfaces[key] = surfaceMask;
}

let commit = 'unknown';
try {
    commit = execFileSync('git', ['-C', radarDir, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim();
} catch {
    // not a git checkout; leave as unknown
}

const source = `/**
 * GENERATED by special-pages/tracker-purposes.mjs. Do not edit by hand.
 *
 * Derived from DuckDuckGo Tracker Radar (${region} crawl, commit ${commit}),
 * licensed CC BY-NC-SA 4.0: https://github.com/duckduckgo/tracker-radar
 *
 * Keys are lower-cased company display names. Values are bitmasks over
 * \`PURPOSE_ORDER\` (eg: 1 = ${PURPOSES[0].id}, 2 = ${PURPOSES[1].id}, 4 = ${PURPOSES[2].id}) or
 * \`SURFACE_ORDER\` (eg: 1 = ${SURFACES[0].id}, 2 = ${SURFACES[1].id}).
 */

/** @type {import('../utils/purposes.js').PurposeId[]} */
export const PURPOSE_ORDER = ${JSON.stringify(PURPOSES.map((p) => p.id))};

/** @type {Record<string, number>} */
export const TRACKER_PURPOSES = ${JSON.stringify(table)};

/** @type {import('../utils/purposes.js').SurfaceId[]} */
export const SURFACE_ORDER = ${JSON.stringify(SURFACES.map((p) => p.id))};

/**
 * What each company's scripts are known to read to recognize a device
 * @type {Record<string, number>}
 */
export const TRACKER_SURFACES = ${JSON.stringify(surfaces)};
`;

const config = await prettier.resolveConfig(OUTPUT);
writeFileSync(OUTPUT, await prettier.format(source, { ...config, filepath: OUTPUT }));
console.log(`✅ wrote ${Object.keys(table).length} purposes and ${Object.keys(surfaces).length} fingerprinting entries to ${OUTPUT}`);
